#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include "my_malloc.h"

int main()
{
    // Тест 1: Базовое выделение и запись данных
    printf("[Тест 1] Выделение памяти под строку...\n");
    // Выделяем 80 байт, чтобы кириллическая строка гарантированно поместилась
    char *str = (char *) my_malloc(80);
    if (str == NULL)
    {
        printf("Ошибка: my_malloc вернул NULL\n");
        exit(EXIT_FAILURE);
    }

    strcpy(str, "Привет, это мой аллокатор!");
    printf("Успешно записано: \"%s\"\n\n", str);

    // Тест 2: Выравнивание и минимальный размер
    printf("[Тест 2] Проверка микро-аллокации (запрос 4 байт)...\n");
    // Должно выровняться до 16 байт (минимум для хранения указателей при free)
    int *num = (int *)my_malloc(sizeof(int));
    if (num != NULL) {
        *num = 42;
        printf("Успешно записано число: %d\n\n", *num);
    }

    // Тест 3: Множественное выделение (создание цепочки)
    printf("[Тест 3] Выделение нескольких блоков подряд...\n");
    char *p1 = (char *)my_malloc(100);
    char *p2 = (char *)my_malloc(100);
    char *p3 = (char *)my_malloc(100);

    strcpy(p1, "Блок 1");
    strcpy(p2, "Блок 2");
    strcpy(p3, "Блок 3");
    printf("Данные блоков: '%s', '%s', '%s'\n\n", p1, p2, p3);

    // Тест 4: Освобождение и повторное использование (Разделение блока)
    printf("[Тест 4] Освобождаем Блок 2 и пытаемся занять его часть...\n");
    my_free(p2); // Теперь в списке свободных появился кусок ~100 байт

    // Запрашиваем 40 байт. Строка "Новый Блок 2" занимает 24 байта в UTF-8 — безопасно влезает!
    char *p2_new = (char *)my_malloc(40);
    if (p2_new != NULL) {
        strcpy(p2_new, "Новый Блок 2");
        printf("Адрес старого p2: %p, Адрес нового p2_new: %p\n", (void *)p2, (void *)p2_new);
        printf("Данные: '%s'\n\n", p2_new);
    }

    // Тест 5: Огромная аллокация (Запрос sbrk)
    printf("[Тест 5] Запрос объема памяти, превышающего текущую кучу...\n");
    // Этот запрос гарантированно заставит сработать ветку расширения кучи
    size_t huge_size = CHUNK_SIZE * 3;
    void *huge_ptr = my_malloc(huge_size);
    if (huge_ptr != NULL)
    {
        printf("Успешно выделено %zu байт у операционной системы!\n\n", huge_size);
    }
    else
    {
        printf("Ошибка при выделении огромного блока\n\n");
    }

    // Тест 6: Полная очистка
    printf("[Тест 6] Полное освобождение оставшейся памяти...\n");
    my_free(str);
    my_free(num);
    my_free(p1);
    my_free(p2_new);
    my_free(p3);
    my_free(huge_ptr);
    printf("Память успешно освобождена\n\n");

    return 0;
}